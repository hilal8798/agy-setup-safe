#!/usr/bin/env python3
"""Build ~/.gemini/skill-library/INDEX.md by scanning installed skills.
Read-only with respect to skills: it reads SKILL.md frontmatter
(name + description) and writes only the INDEX.md file."""
import re
from pathlib import Path

home = Path.home()
roots = [home / ".gemini" / "config" / "skills", home / ".gemini" / "skill-library"]
rows = []
for root in roots:
    if not root.is_dir():
        continue
    for skill_md in sorted(root.rglob("SKILL.md")):
        text = skill_md.read_text(encoding="utf-8", errors="ignore")[:2000]
        name = re.search(r"^name:\s*(.+)$", text, re.M)
        desc = re.search(r"^description:\s*(.+)$", text, re.M)
        rows.append((name.group(1).strip() if name else skill_md.parent.name,
                     desc.group(1).strip() if desc else "",
                     str(skill_md.parent.relative_to(home))))
out = home / ".gemini" / "skill-library"
out.mkdir(parents=True, exist_ok=True)
lines = ["# Skill Index (generated by agy-safe-index)", "", f"Total: {len(rows)} skills", "",
         "| Skill | Description | Path |", "| --- | --- | --- |"]
lines += [f"| {n} | {d} | {p} |" for n, d, p in rows]
(out / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Indexed {len(rows)} skills -> {out / 'INDEX.md'}")
